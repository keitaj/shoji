// Command genfixtures creates the mock CAs and certificates under testdata/
// (if they do not exist yet) and writes the Noir fixtures, the inputs of the
// circuits' positive and negative tests (the same file for both circuits:
// circuits/card/src/fixtures.nr and circuits/delegated/src/fixtures.nr).
//
// All data is synthetic. Run from the repository root: go run ./cmd/genfixtures
package main

import (
	"bytes"
	"crypto/rsa"
	"crypto/x509"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"math/big"
	"os"
	"path/filepath"
	"strings"

	"github.com/keitaj/shoji/internal/mockjpki"
	"github.com/keitaj/shoji/internal/proto"
	"github.com/keitaj/shoji/internal/witness"
)

type holderSpec struct {
	name   string // file / fixture name
	ca     string
	holder mockjpki.Holder
}

func main() {
	dir := flag.String("testdata", "testdata", "directory holding mock keys and certificates")
	out := flag.String("out", "circuits/card/src/fixtures.nr,circuits/delegated/src/fixtures.nr", "comma-separated Noir fixture files to write (all get the same content)")
	proverTOML := flag.String("prover-toml", "", "also write circuit inputs for the adult fixture to this path (for benchmarks)")
	inputsJSON := flag.String("inputs-json", "", "also write the same inputs as JSON to this path (for on-device benchmarks)")
	cardFixture := flag.String("card-fixture", "", "also write to this directory what a phone would hold for the adult fixture (cert.der, ca.der, nonce_sig.bin, request.json) and the expected inputs.json")
	flag.Parse()
	log.SetFlags(0)

	decoy, err := mockjpki.OtherName(mockjpki.OIDDateOfBirth, []byte(mockjpki.DateOfBirthValue("19700101")))
	if err != nil {
		log.Fatal(err)
	}
	addr := []byte("東京都千代田区テスト町1-1")
	specs := []holderSpec{
		{"adult", "ca", mockjpki.Holder{Name: "検証 太郎", Gender: "1", DateOfBirth: "19900115", Address: addr}},
		{"adult2", "ca", mockjpki.Holder{Name: "検証 花子", Gender: "2", DateOfBirth: "19850630", Address: addr}},
		{"minor", "ca", mockjpki.Holder{Name: "検証 次郎", Gender: "1", DateOfBirth: "20150401", Address: addr}},
		// A minor whose address attribute contains the bytes of a complete
		// date-of-birth otherName claiming 1970-01-01.
		{"decoy", "ca", mockjpki.Holder{Name: "検証 三郎", Gender: "1", DateOfBirth: "20150401", Address: append(append([]byte{}, addr...), decoy...)}},
		// An adult certified by a CA the verifier does not trust.
		{"other_ca_adult", "ca_other", mockjpki.Holder{Name: "検証 四郎", Gender: "1", DateOfBirth: "19900115", Address: addr}},
	}

	if err := os.MkdirAll(*dir, 0o755); err != nil {
		log.Fatal(err)
	}
	cas := map[string]*mockjpki.CA{}
	for _, name := range []string{"ca", "ca_other"} {
		cas[name] = loadOrCreateCA(filepath.Join(*dir, name), name)
	}

	appID, appID2 := proto.AppID("shoji-test-app"), proto.AppID("shoji-test-app-2")
	nonce := new(big.Int).SetBytes(bytes.Repeat([]byte{0x11}, proto.NonceBytes))
	nonce2 := new(big.Int).SetBytes(bytes.Repeat([]byte{0x22}, proto.NonceBytes))

	var sb strings.Builder
	sb.WriteString("// GENERATED by `go run ./cmd/genfixtures` from testdata/. DO NOT EDIT.\n")
	sb.WriteString("// Synthetic mock data only: no real certificate or personal data.\n\n")
	sb.WriteString("pub struct CaFixture {\n    pub modulus: [u8; 256],\n    pub redc: [u128; 18],\n    pub hash: Field,\n}\n\n")
	sb.WriteString(`pub struct CertFixture {
    pub tbs: [u8; 2048],
    pub tbs_len: u32,
    pub cert_sig: [u8; 256],
    pub user_redc: [u128; 18],
    // Holder modulus and where it / the date-of-birth digits sit in the TBS (for tamper tests).
    pub modulus: [u8; 256],
    pub modulus_offset: u32,
    pub dob_offset: u32,
    // Card signatures over (APP_ID, NONCE), (APP_ID_2, NONCE) and (APP_ID, NONCE_2).
    pub nonce_sig: [u8; 256],
    pub nonce_sig_app2: [u8; 256],
    pub nonce_sig_nonce2: [u8; 256],
    // Expected nullifiers for APP_ID and APP_ID_2, computed independently in Go.
    pub nullifier: Field,
    pub nullifier_app2: Field,
    // Card signature delegating to DELEGATION_SECRET until DELEGATION_EXPIRY.
    pub delegation_sig: [u8; 256],
}

`)
	fmt.Fprintf(&sb, "pub global APP_ID: Field = %s;\n", proto.FieldHex(appID))
	fmt.Fprintf(&sb, "pub global APP_ID_2: Field = %s;\n", proto.FieldHex(appID2))
	fmt.Fprintf(&sb, "pub global NONCE: Field = %s;\n", proto.FieldHex(nonce))
	fmt.Fprintf(&sb, "pub global NONCE_2: Field = %s;\n", proto.FieldHex(nonce2))
	// A delegation made on the tests' "today" (2026-11-23) for the longest time allowed.
	secret := new(big.Int).SetBytes(bytes.Repeat([]byte{0x33}, 31))
	const delegationExpiry = 20261223
	fmt.Fprintf(&sb, "pub global DELEGATION_SECRET: Field = %s;\n", proto.FieldHex(secret))
	fmt.Fprintf(&sb, "pub global DELEGATION_EXPIRY: u32 = %d;\n\n", delegationExpiry)

	for _, name := range []string{"ca", "ca_other"} {
		n := cas[name].Key.PublicKey.N
		h, err := proto.PubkeyHash(n)
		if err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&sb, "pub global %s: CaFixture = CaFixture {\n    modulus: %s,\n    redc: %s,\n    hash: %s,\n};\n\n",
			strings.ToUpper(name), witness.ByteList(witness.ModulusBytes(n)), witness.LimbList(proto.RedcParam(n), false), proto.FieldHex(h))
	}

	for _, s := range specs {
		cert, key := loadOrIssue(*dir, s, cas[s.ca])
		n := key.PublicKey.N
		tbs := cert.RawTBSCertificate
		if len(tbs)+proto.TBSHeadroom > proto.MaxTBSLen {
			log.Fatalf("%s: TBS too long", s.name)
		}
		padded := make([]byte, proto.MaxTBSLen)
		copy(padded, tbs)

		modOff := bytes.Index(tbs, witness.ModulusBytes(n))
		// Offset of the YYYYMMDD digits; the era digit sits one byte before it.
		dobOff := bytes.Index(tbs, []byte(mockjpki.DateOfBirthValue(s.holder.DateOfBirth))) + 1
		if modOff < 0 || dobOff < 1 {
			log.Fatalf("%s: could not locate fixture offsets", s.name)
		}
		sig := func(a, nn *big.Int) string {
			b, err := witness.SignNonce(key, a, nn)
			if err != nil {
				log.Fatal(err)
			}
			return witness.ByteList(b)
		}
		null1, err := proto.Nullifier(n, appID)
		if err != nil {
			log.Fatal(err)
		}
		null2, _ := proto.Nullifier(n, appID2)

		fmt.Fprintf(&sb, "pub global %s: CertFixture = CertFixture {\n", strings.ToUpper(s.name))
		fmt.Fprintf(&sb, "    tbs: %s,\n    tbs_len: %d,\n", witness.ByteList(padded), len(tbs))
		fmt.Fprintf(&sb, "    cert_sig: %s,\n", witness.ByteList(cert.Signature))
		fmt.Fprintf(&sb, "    user_redc: %s,\n", witness.LimbList(proto.RedcParam(n), false))
		fmt.Fprintf(&sb, "    modulus: %s,\n    modulus_offset: %d,\n    dob_offset: %d,\n", witness.ByteList(witness.ModulusBytes(n)), modOff, dobOff)
		fmt.Fprintf(&sb, "    nonce_sig: %s,\n    nonce_sig_app2: %s,\n    nonce_sig_nonce2: %s,\n", sig(appID, nonce), sig(appID2, nonce), sig(appID, nonce2))
		fmt.Fprintf(&sb, "    nullifier: %s,\n    nullifier_app2: %s,\n", proto.FieldHex(null1), proto.FieldHex(null2))
		d, err := witness.SignDelegation(key, secret, delegationExpiry)
		if err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&sb, "    delegation_sig: %s,\n};\n\n", witness.ByteList(d.Sig))
	}

	for _, path := range strings.Split(*out, ",") {
		if err := os.WriteFile(path, []byte(sb.String()), 0o644); err != nil {
			log.Fatal(err)
		}
		log.Printf("wrote %s", path)
	}

	if *proverTOML != "" || *inputsJSON != "" || *cardFixture != "" {
		cert, key := loadOrIssue(*dir, specs[0], cas["ca"])
		sig, err := witness.SignNonce(key, appID, nonce)
		if err != nil {
			log.Fatal(err)
		}
		in, err := witness.New(cert, &cas["ca"].Key.PublicKey, sig, appID, nonce, 20261123, 18)
		if err != nil {
			log.Fatal(err)
		}
		if *proverTOML != "" {
			if err := os.WriteFile(*proverTOML, []byte(in.ProverTOML()), 0o600); err != nil {
				log.Fatal(err)
			}
		}
		if *cardFixture != "" {
			must := func(err error) {
				if err != nil {
					log.Fatal(err)
				}
			}
			must(os.MkdirAll(*cardFixture, 0o755))
			inputs, err := in.JSON()
			must(err)
			request, err := json.Marshal(map[string]any{
				"challenge":      proto.ChallengeString(appID, nonce),
				"current_date":   in.CurrentDate,
				"age_threshold":  in.AgeThreshold,
				"ca_pubkey_hash": proto.FieldHex(in.CAPubkeyHash),
			})
			must(err)
			for name, data := range map[string][]byte{
				"cert.der": cert.Raw, "ca.der": cas["ca"].Cert.Raw, "nonce_sig.bin": sig,
				"request.json": request, "inputs.json": inputs,
			} {
				must(os.WriteFile(filepath.Join(*cardFixture, name), data, 0o600))
			}
		}
		if *inputsJSON != "" {
			raw, err := in.JSON()
			if err != nil {
				log.Fatal(err)
			}
			if err := os.WriteFile(*inputsJSON, raw, 0o600); err != nil {
				log.Fatal(err)
			}
		}
	}
}

func loadOrCreateCA(base, name string) *mockjpki.CA {
	if ca, err := mockjpki.LoadCA(base); err == nil {
		return ca
	}
	ca, err := mockjpki.NewCA("shoji mock CA (" + name + ")")
	if err != nil {
		log.Fatal(err)
	}
	if err := ca.Save(base); err != nil {
		log.Fatal(err)
	}
	log.Printf("created mock CA %s", base)
	return ca
}

func loadOrIssue(dir string, s holderSpec, ca *mockjpki.CA) (*x509.Certificate, *rsa.PrivateKey) {
	base := filepath.Join(dir, s.name)
	cert, errC := mockjpki.ReadCertPEM(base + ".pem")
	key, errK := mockjpki.ReadKeyPEM(base + ".key")
	// Reuse an existing certificate only if it is from this CA and still has the
	// current encoding (certificates issued before a format change are replaced).
	current := []byte(mockjpki.DateOfBirthValue(s.holder.DateOfBirth))
	if errC == nil && errK == nil && cert.CheckSignatureFrom(ca.Cert) == nil && bytes.Contains(cert.RawTBSCertificate, current) {
		return cert, key
	}
	cert, key, err := ca.Issue(s.holder)
	if err != nil {
		log.Fatal(err)
	}
	if err := mockjpki.WriteCertPEM(base+".pem", cert); err != nil {
		log.Fatal(err)
	}
	if err := mockjpki.WriteKeyPEM(base+".key", key); err != nil {
		log.Fatal(err)
	}
	log.Printf("issued mock certificate %s", base)
	return cert, key
}
